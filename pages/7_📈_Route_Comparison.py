if st.button("📊 Generate Route Comparison", type="primary"):
    with st.spinner("Calculating baseline and OR-Tools route metrics..."):
        try:
            route_results = optimize_routes()
            if not route_results:
                st.session_state.pop("route_comparison_data", None)
                st.warning("No optimized route is available to compare. Generate a route first.")
            else:
                baseline_distance = 0.0
                optimized_distance = 0.0
                baseline_time = 0.0
                optimized_time = 0.0
                baseline_fuel = 0.0
                optimized_fuel = 0.0
                total_waste = 0.0
                comparison_routes = []

                for route_data in route_results:
                    baseline_locations = baseline_route_for(route_data)
                    baseline_km = route_distance_km(baseline_locations)
                    optimized_km = float(route_data.get("total_distance_km", 0) or 0)
                    optimized_minutes = float(route_data.get("estimated_time_min", 0) or 0)
                    optimized_litres = float(route_data.get("estimated_fuel_l", 0) or 0)

                    # Use the same vehicle fuel rate for its baseline and optimized route.
                    litres_per_km = (
                        optimized_litres / optimized_km
                        if optimized_km > 0
                        else 0.0
                    )
                    baseline_litres = baseline_km * litres_per_km
                    baseline_minutes = (baseline_km / 30.0) * 60.0

                    baseline_distance += baseline_km
                    optimized_distance += optimized_km
                    baseline_time += baseline_minutes
                    optimized_time += optimized_minutes
                    baseline_fuel += baseline_litres
                    optimized_fuel += optimized_litres
                    total_waste += float(route_data.get("total_waste_kg", 0) or 0)

                    comparison_routes.append({
                        "vehicle_number": route_data.get("vehicle_number", "Vehicle"),
                        "baseline_route": baseline_locations,
                        "optimized_route": route_data["route"],
                    })

                distance_delta = baseline_distance - optimized_distance
                distance_pct = (distance_delta / baseline_distance * 100) if baseline_distance > 0 else 0.0
                fuel_delta = baseline_fuel - optimized_fuel
                fuel_pct = (fuel_delta / baseline_fuel * 100) if baseline_fuel > 0 else 0.0
                time_delta = baseline_time - optimized_time
                time_pct = (time_delta / baseline_time * 100) if baseline_time > 0 else 0.0

                st.session_state["route_comparison_data"] = {
                    "baseline_distance": baseline_distance,
                    "optimized_distance": optimized_distance,
                    "baseline_time": baseline_time,
                    "optimized_time": optimized_time,
                    "baseline_fuel": baseline_fuel,
                    "optimized_fuel": optimized_fuel,
                    "distance_delta": distance_delta,
                    "distance_pct": distance_pct,
                    "fuel_delta": fuel_delta,
                    "fuel_pct": fuel_pct,
                    "time_delta": time_delta,
                    "time_pct": time_pct,
                    "total_waste": total_waste,
                    "routes": comparison_routes,
                }
                st.success("✅ Comparison generated.")
        except Exception as exc:
            st.error(f"Could not generate comparison: {exc}")


