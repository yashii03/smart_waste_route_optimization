def haversine_km(point_a, point_b):
    """Return straight-line distance in km between two lat/lon dictionaries."""
    earth_radius_km = 6371.0
    lat1 = math.radians(float(point_a["latitude"]))
    lon1 = math.radians(float(point_a["longitude"]))
    lat2 = math.radians(float(point_b["latitude"]))
    lon2 = math.radians(float(point_b["longitude"]))

    dlat = lat2 - lat1
    dlon = lon2 - lon1
    a = (
        math.sin(dlat / 2) ** 2
        + math.cos(lat1) * math.cos(lat2) * math.sin(dlon / 2) ** 2
    )
    return 2 * earth_radius_km * math.asin(min(1.0, math.sqrt(a)))


def route_distance_km(locations):
    total = 0.0
    for index in range(len(locations) - 1):
        total += haversine_km(locations[index], locations[index + 1])
    return total


def baseline_route_for(route_data):
    """Keep each vehicle's assigned bins, but visit them in bin-code order."""
    locations = route_data["route"]
    depot = next(
        location for location in locations
        if location.get("bin_code") == "DEPOT"
    )
    bins = [
        location for location in locations
        if location.get("bin_code") != "DEPOT"
    ]
    bins.sort(key=lambda item: item.get("bin_code", ""))
    return [depot, *bins, depot]


def format_route(locations):
    labels = []
    for location in locations:
        if location.get("bin_code") == "DEPOT":
            labels.append(f"🏫 {location.get('location_name', 'Depot')}")
        else:
            labels.append(f"🗑️ {location.get('bin_code', 'Bin')}")
    return " → ".join(labels)


